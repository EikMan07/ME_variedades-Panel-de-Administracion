-- ==============================================================================
-- 4. TRIGGER: DESCONTAR STOCK AUTOMÁTICO AL REGISTRAR PEDIDO
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.fn_descontar_stock_pedido()
RETURNS TRIGGER AS $$
DECLARE
    v_stock_actual INTEGER;
BEGIN
    -- Obtener el stock actual del producto
    SELECT stock INTO v_stock_actual FROM public.productos WHERE id = NEW.producto_id;
    
    -- Validar que haya stock suficiente
    IF v_stock_actual < NEW.cantidad THEN
        RAISE EXCEPTION 'Stock insuficiente para el producto ID %. Stock actual: %, solicitado: %', NEW.producto_id, v_stock_actual, NEW.cantidad;
    END IF;

    -- Descontar el stock en la tabla de productos
    UPDATE public.productos
    SET stock = stock - NEW.cantidad
    WHERE id = NEW.producto_id;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_descontar_stock_pedido ON public.pedidos;
CREATE TRIGGER tr_descontar_stock_pedido
AFTER INSERT ON public.pedidos
FOR EACH ROW
EXECUTE FUNCTION public.fn_descontar_stock_pedido();

