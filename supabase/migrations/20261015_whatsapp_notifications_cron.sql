-- 4. FUNCIÓN AUXILIAR: url_encode (Codificación segura de caracteres)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.url_encode(data text)
RETURNS text AS $$
DECLARE
    r text := '';
    b bytea;
    i int;
    len int;
    byte_val int;
BEGIN
    IF data IS NULL THEN
        RETURN '';
    END IF;
    b := convert_to(data, 'UTF-8');
    len := octet_length(b);
    FOR i IN 0..(len - 1) LOOP
        byte_val := get_byte(b, i);
        IF (byte_val >= 48 AND byte_val <= 57) OR
           (byte_val >= 65 AND byte_val <= 90) OR
           (byte_val >= 97 AND byte_val <= 122) OR
           byte_val = 45 OR byte_val = 46 OR byte_val = 95 OR byte_val = 126 THEN
            r := r || chr(byte_val);
        ELSE
            r := r || '%' || upper(lpad(to_hex(byte_val), 2, '0'));
        END IF;
    END LOOP;
    RETURN r;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

-- ==============================================================================
-- 5. FUNCIÓN: enviar_whatsapp_admin (Despacho a CallMeBot con pg_net)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.enviar_whatsapp_admin(p_mensaje text)
RETURNS bigint AS $$
DECLARE
    v_phone text;
    v_apikey text;
    v_url text;
    v_encoded_msg text;
    v_request_id bigint := NULL;
BEGIN
    SELECT valor INTO v_phone FROM public.app_config WHERE clave = 'whatsapp_admin_phone';
    SELECT valor INTO v_apikey FROM public.app_config WHERE clave = '';

    IF v_phone IS NULL OR v_phone = '' OR v_apikey IS NULL OR v_apikey = '' THEN
        RAISE NOTICE 'CallMeBot no configurado en app_config. Notificación guardada solo en base de datos.';
        RETURN NULL;
    END IF;

    v_phone := regexp_replace(v_phone, '\D', '', 'g');
    IF length(v_phone) = 8 THEN
        v_phone := '506' || v_phone;
    END IF;

    v_encoded_msg := public.url_encode(p_mensaje);
    v_url := 'https://api.callmebot.com/whatsapp.php?phone=' || v_phone || '&text=' || v_encoded_msg || '&apikey=' || v_apikey;

    BEGIN
        SELECT net.http_get(
            url := v_url,
            timeout_milliseconds := 8000
        ) INTO v_request_id;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'Error al ejecutar net.http_get hacia CallMeBot: %', SQLERRM;
        RETURN NULL;
    END;

    RETURN v_request_id;
END;
$$ LANGUAGE plpgsql VOLATILE;

