-- 7. TRIGGER: Alerta de Nueva Venta Registrada
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.fn_tr_alerta_nueva_venta()
RETURNS TRIGGER AS $$
DECLARE
    v_cliente_nombre text := 'Cliente';
    v_producto_nombre text := 'Producto';
    v_enabled text;
    v_total_formateado text;
    v_modalidad text;
BEGIN
    SELECT nombre_completo INTO v_cliente_nombre FROM public.clientes WHERE id = NEW.cliente_id;
    SELECT nombre INTO v_producto_nombre FROM public.productos WHERE id = NEW.producto_id;

    v_total_formateado := to_char(COALESCE(NEW.total, 0), 'FM999,999,990');
    v_modalidad := UPPER(COALESCE(NEW.modalidad, 'contado'));

    INSERT INTO public.notificaciones (tipo, titulo, mensaje, metadata)
    VALUES (
        'venta',
        'Nueva Venta Registrada',
        COALESCE(v_cliente_nombre, 'Cliente') || ' adquirió ' || COALESCE(v_producto_nombre, 'artículo') || ' por ₡' || v_total_formateado || ' (' || v_modalidad || ').',
        jsonb_build_object(
            'pedido_id', NEW.id,
            'cliente_id', NEW.cliente_id,
            'cliente_nombre', v_cliente_nombre,
            'producto_id', NEW.producto_id,
            'producto_nombre', v_producto_nombre,
            'total', NEW.total,
            'modalidad', NEW.modalidad
        )
    );

    SELECT valor INTO v_enabled FROM public.app_config WHERE clave = 'whatsapp_notif_ventas_enabled';
    IF COALESCE(v_enabled, 'true') = 'true' THEN
        PERFORM public.enviar_whatsapp_admin(
            '🛍️ *NUEVA VENTA REGISTRADA | ME Variedades*' || E'\n\n' ||
            '• *Cliente:* ' || COALESCE(v_cliente_nombre, 'Cliente General') || E'\n' ||
            '• *Artículo:* ' || COALESCE(v_producto_nombre, 'Mercancía') || ' (Cant: ' || NEW.cantidad || ')' || E'\n' ||
            '• *Total:* ₡' || v_total_formateado || E'\n' ||
            '• *Modalidad:* ' || v_modalidad || E'\n\n' ||
            '✨ _Registrado exitosamente en Centro de Control ME Variedades._'
        );
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

