-- 9. FUNCIÓN Y CRON: Recordatorios Diarios de Cumpleaños a las 8:00 AM
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.verificar_cumpleanos_diarios()
RETURNS integer AS $$
DECLARE
    v_dia_hoy int;
    v_mes_hoy int;
    v_cliente record;
    v_link_wa text;
    v_tel_limpio text;
    v_mensaje_wa text;
    v_contador int := 0;
    v_ya_notificado boolean;
    v_enabled text;
BEGIN
    v_dia_hoy := EXTRACT(DAY FROM (NOW() AT TIME ZONE 'America/Costa_Rica'))::int;
    v_mes_hoy := EXTRACT(MONTH FROM (NOW() AT TIME ZONE 'America/Costa_Rica'))::int;

    SELECT valor INTO v_enabled FROM public.app_config WHERE clave = 'whatsapp_notif_cumpleanos_enabled';

    FOR v_cliente IN 
        SELECT id, nombre_completo, telefono 
        FROM public.clientes
        WHERE (dia_cumpleanos = v_dia_hoy AND mes_cumpleanos = v_mes_hoy)
           OR (fecha_nacimiento IS NOT NULL 
               AND EXTRACT(DAY FROM fecha_nacimiento)::int = v_dia_hoy 
               AND EXTRACT(MONTH FROM fecha_nacimiento)::int = v_mes_hoy)
    LOOP
        SELECT EXISTS (
            SELECT 1 FROM public.notificaciones
            WHERE tipo = 'cumpleanos'
              AND (metadata->>'cliente_id')::bigint = v_cliente.id
              AND (created_at AT TIME ZONE 'America/Costa_Rica')::date = (NOW() AT TIME ZONE 'America/Costa_Rica')::date
        ) INTO v_ya_notificado;

        IF NOT v_ya_notificado THEN
            v_tel_limpio := regexp_replace(COALESCE(v_cliente.telefono, ''), '\D', '', 'g');
            IF length(v_tel_limpio) = 8 THEN
                v_tel_limpio := '506' || v_tel_limpio;
            END IF;

            v_link_wa := 'https://wa.me/' || v_tel_limpio || '?text=' || 
                         public.url_encode('¡Hola ' || v_cliente.nombre_completo || '! En ME Variedades te deseamos un muy feliz cumpleaños 🎉🎂 Esperamos que pases un día maravilloso.');

            INSERT INTO public.notificaciones (tipo, titulo, mensaje, metadata)
            VALUES (
                'cumpleanos',
                '¡Cumpleaños de Hoy!',
                v_cliente.nombre_completo || ' celebra su cumpleaños hoy (' || v_dia_hoy || '/' || v_mes_hoy || ').',
                jsonb_build_object(
                    'cliente_id', v_cliente.id,
                    'cliente_nombre', v_cliente.nombre_completo,
                    'telefono', v_cliente.telefono,
                    'link_whatsapp', v_link_wa
                )
            );

            IF COALESCE(v_enabled, 'true') = 'true' THEN
                v_mensaje_wa := '🎉 *RECORDATORIO DE CUMPLEAÑOS | ME Variedades*' || E'\n\n' ||
                                'Hoy está de cumpleaños: *' || v_cliente.nombre_completo || '*' || E'\n' ||
                                '• *Teléfono:* ' || COALESCE(v_cliente.telefono, 'No registrado') || E'\n\n' ||
                                '📲 Puedes felicitar al cliente con un toque desde este enlace:' || E'\n' ||
                                v_link_wa;

                PERFORM public.enviar_whatsapp_admin(v_mensaje_wa);
            END IF;

            v_contador := v_contador + 1;
        END IF;
    END LOOP;

    RETURN v_contador;
END;
$$ LANGUAGE plpgsql VOLATILE;

-- Programación de pg_cron: 14:00 UTC = 8:00 AM hora local Costa Rica
DO $$
BEGIN
    PERFORM cron.unschedule('cumpleanos-diarios-8am');
EXCEPTION
    WHEN OTHERS THEN NULL;
END $$;

DO $$
BEGIN
    PERFORM cron.schedule('cumpleanos-diarios-8am', '0 14 * * *', $$SELECT public.verificar_cumpleanos_diarios();$$);
EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE 'pg_cron schedule omitido en entorno sin extensión activa: %', SQLERRM;
END $$;
