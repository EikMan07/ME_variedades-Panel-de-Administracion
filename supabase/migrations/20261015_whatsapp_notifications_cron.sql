-- 8. TRIGGER: Alerta de Pago / Abono Recibido
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.fn_tr_alerta_nuevo_pago()
RETURNS TRIGGER AS $$
DECLARE
    v_cliente_nombre text := 'Cliente';
    v_monto_abono numeric(12,2) := 0;
    v_enabled text;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_monto_abono := COALESCE(NEW.monto_pagado, 0);
    ELSIF TG_OP = 'UPDATE' THEN
        v_monto_abono := COALESCE(NEW.monto_pagado, 0) - COALESCE(OLD.monto_pagado, 0);
    END IF;

    IF v_monto_abono > 0 THEN
        SELECT nombre_completo INTO v_cliente_nombre FROM public.clientes WHERE id = NEW.cliente_id;

        INSERT INTO public.notificaciones (tipo, titulo, mensaje, metadata)
        VALUES (
            'pago',
            'Nuevo Pago / Abono Recibido',
            'Se registró un abono de ₡' || to_char(v_monto_abono, 'FM999,999,990') || ' de ' || COALESCE(v_cliente_nombre, 'Cliente') || ' (' || NEW.concepto || '). Saldo restante: ₡' || to_char(COALESCE(NEW.saldo_pendiente, 0), 'FM999,999,990') || '.',
            jsonb_build_object(
                'pago_id', NEW.id,
                'cliente_id', NEW.cliente_id,
                'cliente_nombre', v_cliente_nombre,
                'monto_abono', v_monto_abono,
                'saldo_pendiente', NEW.saldo_pendiente,
                'concepto', NEW.concepto
            )
        );

        SELECT valor INTO v_enabled FROM public.app_config WHERE clave = 'whatsapp_notif_pagos_enabled';
        IF COALESCE(v_enabled, 'true') = 'true' THEN
            PERFORM public.enviar_whatsapp_admin(
                '💰 *ABONO RECIBIDO | ME Variedades*' || E'\n\n' ||
                '• *Cliente:* ' || COALESCE(v_cliente_nombre, 'Cliente') || E'\n' ||
                '• *Monto Abonado:* ₡' || to_char(v_monto_abono, 'FM999,999,990') || E'\n' ||
                '• *Concepto:* ' || NEW.concepto || E'\n' ||
                '• *Saldo Restante:* ₡' || to_char(COALESCE(NEW.saldo_pendiente, 0), 'FM999,999,990') || E'\n\n' ||
                '✅ _Cuentas por cobrar actualizadas en tiempo real._'
            );
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

