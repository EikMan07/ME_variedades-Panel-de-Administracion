-- 6. TRIGGER: Alerta de Stock Bajo / Agotado
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.fn_tr_alerta_stock_producto()
RETURNS TRIGGER AS $$
DECLARE
    v_enabled text;
    v_mensaje text;
BEGIN
    IF NEW.stock <= 3 THEN
        IF TG_OP = 'UPDATE' AND OLD.stock <= NEW.stock THEN
            RETURN NEW;
        END IF;

        v_mensaje := 'El producto "' || NEW.nombre || '" tiene stock crítico (' || NEW.stock || ' unidad(es) restante(s)).';

        INSERT INTO public.notificaciones (tipo, titulo, mensaje, metadata)
        VALUES (
            CASE WHEN NEW.stock = 0 THEN 'stock_agotado' ELSE 'stock_bajo' END,
            CASE WHEN NEW.stock = 0 THEN 'Producto Agotado' ELSE 'Stock Crítico' END,
            v_mensaje,
            jsonb_build_object(
                'producto_id', NEW.id,
                'producto_nombre', NEW.nombre,
                'stock_actual', NEW.stock
            )
        );

        SELECT valor INTO v_enabled FROM public.app_config WHERE clave = 'whatsapp_notif_stock_enabled';
        IF COALESCE(v_enabled, 'true') = 'true' THEN
            PERFORM public.enviar_whatsapp_admin(
                '⚠️ *ALERTA DE INVENTARIO | ME Variedades*' || E'\n\n' ||
                '• *Producto:* ' || NEW.nombre || E'\n' ||
                '• *Stock Restante:* ' || NEW.stock || ' unidad(es)' || E'\n' ||
                '• *Estado:* ' || (CASE WHEN NEW.stock = 0 THEN 'AGOTADO' ELSE 'CRÍTICO' END) || E'\n\n' ||
                '💡 _Se sugiere coordinar reposición en el panel administrativo._'
            );
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_alerta_stock_producto ON public.productos;
CREATE TRIGGER tr_alerta_stock_producto
AFTER INSERT OR UPDATE OF stock ON public.productos
FOR EACH ROW
EXECUTE FUNCTION public.fn_tr_alerta_stock_producto();

