-- ==============================================================================
-- SCRIPT SQL DEFINITIVO: DESBLOQUEO Y CORRECCIÓN DE POLÍTICAS RLS EN PRODUCCIÓN
-- PLATAFORMA "ME VARIEDADES" — PANEL ADMINISTRATIVO
-- ==============================================================================
-- Este script es 100% IDEMPOTENTE y está listo para ser ejecutado directamente en
-- el SQL Editor del Dashboard de Supabase (https://supabase.com/dashboard/project/_/sql).
-- 
-- Objetivo:
-- 1. Garantizar permisos globales a los roles 'anon' y 'authenticated' para que
--    la app móvil y web operen sin bloqueos silenciosos ni 'Total Clientes: 0'.
-- 2. Asegurar la existencia de las tablas operativas (incluyendo 'notificaciones').
-- 3. Configurar políticas RLS permisivas (SELECT, INSERT, UPDATE, DELETE) para anon y authenticated.
-- 4. Habilitar la publicación en tiempo real (Supabase Realtime) para reactividad instantánea.
-- ==============================================================================

-- 1. EXTENSIONES REQUERIDAS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==============================================================================
-- 2. ASEGURAR EXISTENCIA DE TODAS LAS TABLAS OPERATIVAS
-- ==============================================================================

-- A) TABLA: clientes
CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo TEXT NOT NULL,
    telefono TEXT NOT NULL,
    fecha_nacimiento DATE,
    dia_cumpleanos INTEGER,
    mes_cumpleanos INTEGER,
    estado_cuenta TEXT DEFAULT 'al_dia',
    pedidos_activos INTEGER DEFAULT 0,
    saldo_pendiente NUMERIC(12, 2) DEFAULT 0,
    prestamos_abiertos INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- B) TABLA: productos
CREATE TABLE IF NOT EXISTS public.productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    tipo TEXT NOT NULL,
    genero TEXT,
    costo NUMERIC(12, 2) NOT NULL DEFAULT 0,
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    imagen_url TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- C) TABLA: pedidos
CREATE TABLE IF NOT EXISTS public.pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
    producto_id BIGINT REFERENCES public.productos(id) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    estado TEXT DEFAULT 'Activo',
    cuotas JSONB DEFAULT '[]'::jsonb,
    tipo_plazo TEXT,
    num_plazos INTEGER,
    modalidad TEXT DEFAULT 'contado',
    precio_facturacion NUMERIC(12, 2),
    precio_venta_real NUMERIC(12, 2),
    moratoria_tipo TEXT DEFAULT 'semana',
    moratoria_monto NUMERIC(12, 2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- D) TABLA: pagos
CREATE TABLE IF NOT EXISTS public.pagos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
    concepto TEXT NOT NULL,
    pedido_asociado TEXT,
    monto_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    monto_pagado NUMERIC(12, 2) NOT NULL DEFAULT 0,
    saldo_pendiente NUMERIC(12, 2) NOT NULL DEFAULT 0,
    fecha_acordada DATE,
    tipo_pago TEXT,
    estado TEXT DEFAULT 'pendiente',
    abonos JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- E) TABLA: prestamos
CREATE TABLE IF NOT EXISTS public.prestamos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE CASCADE,
    nombre_tercero TEXT,
    telefono TEXT,
    monto_capital NUMERIC(12, 2) NOT NULL DEFAULT 0,
    tasa_interes NUMERIC(5, 2) NOT NULL DEFAULT 0,
    total_devolver NUMERIC(12, 2) NOT NULL DEFAULT 0,
    saldo_pendiente NUMERIC(12, 2) NOT NULL DEFAULT 0,
    fecha_entrega DATE DEFAULT CURRENT_DATE NOT NULL,
    fecha_limite DATE NOT NULL,
    estado TEXT DEFAULT 'al_dia',
    abonos JSONB DEFAULT '[]'::jsonb,
    cuotas JSONB DEFAULT '[]'::jsonb,
    tipo_plazo TEXT,
    num_plazos INTEGER,
    moratoria_tipo TEXT DEFAULT 'semana',
    moratoria_monto NUMERIC(12, 2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- F) TABLA: notificaciones
CREATE TABLE IF NOT EXISTS public.notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo TEXT NOT NULL,
    titulo TEXT NOT NULL,
    mensaje TEXT NOT NULL,
    leida BOOLEAN NOT NULL DEFAULT false,
    metadata JSONB DEFAULT '{}'::jsonb,
    enviada_whatsapp BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('America/Costa_Rica', NOW()) NOT NULL
);

-- G) TABLA: tipo_cambio_historial
CREATE TABLE IF NOT EXISTS public.tipo_cambio_historial (
    fecha DATE PRIMARY KEY,
    compra NUMERIC(10, 4) NOT NULL,
    venta NUMERIC(10, 4) NOT NULL,
    fuente TEXT DEFAULT 'BCCR',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- ==============================================================================
-- 3. PERMISOS GENERALES DEL ESQUEMA Y TABLAS PARA ROLES SUPABASE
-- ==============================================================================
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON ROUTINES TO anon, authenticated, service_role;

-- ==============================================================================
-- 4. CONFIGURACIÓN IDEMPOTENTE DE POLÍTICAS RLS (CRUD COMPLETO ANON + AUTH)
-- ==============================================================================

-- Macro para configurar de forma unificada y limpia cada tabla
DO $$
DECLARE
    tablas TEXT[] := ARRAY[
        'clientes',
        'productos',
        'pedidos',
        'pagos',
        'prestamos',
        'notificaciones',
        'tipo_cambio_historial'
    ];
    t TEXT;
BEGIN
    FOREACH t IN ARRAY tablas
    LOOP
        -- 1. Habilitar RLS en la tabla
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t);

        -- 2. Eliminar cualquier política previa que pueda estar causando conflictos
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Permitir_todo_anon_auth_' || t, t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Acceso total a ' || t, t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Allow all for authenticated users', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Enable read access for all users', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Enable insert for all users', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Enable update for all users', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Enable delete for all users', t);

        -- 3. Crear política permisiva integral (SELECT, INSERT, UPDATE, DELETE para anon y authenticated)
        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);',
            'Permitir_todo_anon_auth_' || t,
            t
        );
        
        RAISE NOTICE 'Política RLS aplicada correctamente a la tabla: %', t;
    END LOOP;
END $$;

-- ==============================================================================
-- 5. PUBLICACIÓN REALTIME PARA REACTIVIDAD EN VIVO EN EL NAVEGADOR
-- ==============================================================================
DO $$
DECLARE
    tablas_realtime TEXT[] := ARRAY[
        'clientes',
        'productos',
        'pedidos',
        'pagos',
        'prestamos',
        'notificaciones',
        'tipo_cambio_historial'
    ];
    t TEXT;
BEGIN
    FOREACH t IN ARRAY tablas_realtime
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_publication_tables 
            WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = t
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I;', t);
            RAISE NOTICE 'Tabla agregada a supabase_realtime: %', t;
        END IF;
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE 'Aviso en publicación realtime: %', SQLERRM;
END $$;

-- ==============================================================================
-- 6. VERIFICACIÓN FINAL: CONSULTA DE COMPROBACIÓN
-- ==============================================================================
-- Si todo está configurado correctamente, la siguiente consulta mostrará una
-- fila con 'Permitir_todo_anon_auth_...' por cada tabla con roles {anon,authenticated}.
SELECT 
    tablename AS "Tabla", 
    policyname AS "Política RLS", 
    roles AS "Roles Autorizados", 
    cmd AS "Operaciones",
    qual AS "Condición USING", 
    with_check AS "Condición WITH CHECK"
FROM pg_policies 
WHERE schemaname = 'public'
ORDER BY tablename;
